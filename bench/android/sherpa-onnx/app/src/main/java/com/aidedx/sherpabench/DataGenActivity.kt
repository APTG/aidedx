/**
 * issue #130 Part 2 — prompts a sentence from `datagen-sentences.json` (pushed to filesDir,
 * generated by `scripts/generate-datagen-sentences.mjs`), records it from the phone mic,
 * transcribes with both NeMo Parakeet-v3 and Whisper, shows a fast on-device slot check, and
 * saves the WAV + both raw transcripts for PC-side scoring (issue #130 Part 3). Not a product
 * UI — same non-goal `bench/android/`'s other activities already state, a data-collection
 * tool for the maintainer's own device, not anything shipped.
 *
 * Loads both recognizers once at startup, not per-clip — Parakeet int8 (~639 MB) + whisper-
 * small int8 (~250 MB) together should fit comfortably inside a Pixel 7a's 8 GB
 * (`docs/nemo-parakeet-comparison.md` measured each alone with no OOM issues). If a lower-RAM
 * device OOM-kills the process, the documented fallback is load→transcribe→release per model
 * per clip instead — not implemented here; flip to that if eager dual-load doesn't hold up in
 * practice (this session has no working `adb`, so it could not be verified on real hardware —
 * see the PR description).
 *
 * The on-device verdict below is literal `slotTruth` token containment against the raw
 * transcript (~normalize, then regex-match each particle/material, check each energy/target
 * value+unit) — NOT a port of the real matcher/corrector (`src/lib/intent/matcher.ts`,
 * `src/lib/asr/correct/core.ts`), which stay TypeScript and single-sourced. This is a fast,
 * approximate "did it hear my sentence?" indicator for the phone screen; the PC-side import
 * (Part 3) re-scores every saved transcript through the real pipeline for the number that
 * actually counts.
 *
 * Intent extras (all optional except `speaker`):
 *   speaker             (required) output subdirectory name under filesDir/out/
 *   lang                "en" | "pl" | "both" (default "both") — which language(s) to prompt;
 *                       "both" interleaves each tuple's EN card immediately before its PL card
 *   sentences_file      path relative to filesDir (default "datagen-sentences.json")
 *   parakeet_model_dir  path relative to filesDir (default "model-parakeet")
 *   whisper_model_dir   path relative to filesDir (default "model-whisper")
 *   hotwords_file       path relative to filesDir — a *file*, not a plain string extra, since
 *                       `adb shell`'s remote re-tokenization mangles the hotwords syntax's own
 *                       "/" and ":" punctuation when passed as `-e hotwords "..."` directly
 *                       (`docs/nemo-parakeet-comparison.md` §8) — same convention BenchActivity
 *                       already uses
 *   decoding_method     (default "modified_beam_search" — required for hotwords to take effect)
 *   num_threads         (default 2)
 *   force               "true" to re-record cards already committed in a prior session
 *                       (default: skip already-committed ids, same as
 *                       `scripts/record-session-pl.sh --force` semantics)
 *
 * Output, under filesDir/out/<speaker>/:
 *   <id>-<lang>.wav               16 kHz mono PCM
 *   session.json                 per-take detail: id, lang, display, canonical, wav path,
 *                                 per-model {raw, secs}, slot-check hits — rewritten after
 *                                 every "Keep" tap so a killed/backgrounded app loses nothing
 *   results-parakeet-<lang>.json  the existing {modelId, dtype, withPrompt, loadS, records[]}
 *   results-whisper-<lang>.json   contract scripts/e2e-audio-intents.ts / asr-score-slots-
 *                                 generic.mjs already consume — no scoring-script changes needed
 */
