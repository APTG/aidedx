        }
    }

    private fun writeJsonFile(file: File, entries: List<String>) {
        val json = "[\n" + entries.joinToString(",\n") { "  $it" } + "\n]\n"
        FileOutputStream(file).use { it.write(json.toByteArray()) }
    }

    private fun writeResultsFile(file: File, modelId: String, loadS: Double, records: List<String>) {
        val json = "{\n" +
            "  \"modelId\": ${jsonStr(modelId)},\n" +
            "  \"dtype\": \"device\",\n" +
            "  \"withPrompt\": false,\n" +
            "  \"loadS\": $loadS,\n" +
            "  \"records\": [\n" +
            records.joinToString(",\n") { "    $it" } +
            "\n  ]\n" +
            "}\n"
        FileOutputStream(file).use { it.write(json.toByteArray()) }
    }

    /** Standard 44-byte PCM WAV header, mono 16-bit. */
    private fun writeWavFile(file: File, pcm: ShortArray, sampleRate: Int) {
        val dataLen = pcm.size * 2
        RandomAccessFile(file, "rw").use { raf ->
            raf.setLength(0)
            fun writeIntLE(v: Int) {
                raf.write(byteArrayOf((v and 0xff).toByte(), ((v shr 8) and 0xff).toByte(), ((v shr 16) and 0xff).toByte(), ((v shr 24) and 0xff).toByte()))
            }
            fun writeShortLE(v: Int) {
                raf.write(byteArrayOf((v and 0xff).toByte(), ((v shr 8) and 0xff).toByte()))
            }
            raf.writeBytes("RIFF")
            writeIntLE(36 + dataLen)
            raf.writeBytes("WAVE")
            raf.writeBytes("fmt ")
            writeIntLE(16)
            writeShortLE(1) // PCM
            writeShortLE(1) // mono
            writeIntLE(sampleRate)
            writeIntLE(sampleRate * 2) // byte rate = sampleRate * channels * bytesPerSample
            writeShortLE(2) // block align
            writeShortLE(16) // bits per sample
            raf.writeBytes("data")
            writeIntLE(dataLen)
            val bytes = ByteArray(dataLen)
            for (i in pcm.indices) {
                val v = pcm[i].toInt()
                bytes[i * 2] = (v and 0xff).toByte()
                bytes[i * 2 + 1] = ((v shr 8) and 0xff).toByte()
            }
            raf.write(bytes)
        }
    }

