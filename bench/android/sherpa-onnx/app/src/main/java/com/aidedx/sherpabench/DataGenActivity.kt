    private fun appendLog(line: String) {
        log.append(line).append('\n')
        runOnUiThread { logText.text = log.toString() }
    }

    // -------------------------------------------------------------------------------------
    // Setup: load both recognizers, parse the sentence deck, resume any prior session.
    // -------------------------------------------------------------------------------------
    private fun setup() {
        speaker = intent.getStringExtra("speaker") ?: run {
            appendLog("FAILED: missing required intent extra \"speaker\"")
            return
        }
        val lang = intent.getStringExtra("lang") ?: "both"
        val sentencesFile = intent.getStringExtra("sentences_file") ?: "datagen-sentences.json"
        val parakeetModelDir = intent.getStringExtra("parakeet_model_dir") ?: "model-parakeet"
        val whisperModelDir = intent.getStringExtra("whisper_model_dir") ?: "model-whisper"
        val hotwordsFile = intent.getStringExtra("hotwords_file")
        val decodingMethod = intent.getStringExtra("decoding_method") ?: "modified_beam_search"
        val numThreads = intent.getIntExtra("num_threads", 2)
        val force = intent.getBooleanExtra("force", false)

        hotwords = hotwordsFile?.let { File(filesDir, it).readText().trim() }
        outDir = File(File(filesDir, "out"), speaker)
        outDir.mkdirs()

        appendLog("Loading Parakeet ($parakeetModelDir)...")
        try {
            parakeetRecognizer = loadParakeet(parakeetModelDir, numThreads, decodingMethod)
        } catch (e: Exception) {
            appendLog("FAILED to load Parakeet: ${stackTraceOf(e)}")
            return
        }
        appendLog("Parakeet loaded in ${"%.1f".format(parakeetLoadS)}s")

        appendLog("Loading Whisper ($whisperModelDir)...")
        try {
            whisperRecognizer = loadWhisper(whisperModelDir, numThreads)
        } catch (e: Exception) {
            appendLog("FAILED to load Whisper: ${stackTraceOf(e)}")
            return
        }
        appendLog("Whisper loaded in ${"%.1f".format(whisperLoadS)}s")

        val sentencesPath = File(filesDir, sentencesFile)
        if (!sentencesPath.exists()) {
            appendLog("FAILED: $sentencesPath does not exist (push it first)")
            return
        }
        val fullDeck = loadDeck(sentencesPath, lang)

        if (!force) {
            loadPriorSession()
        }
        deck = fullDeck.filter { it.cardId !in committedCardIds }
        appendLog(
            "Deck: ${fullDeck.size} cards, ${committedCardIds.size} already committed, " +
                "${deck.size} remaining.",
        )

        runOnUiThread {
            recordButton.isEnabled = true
            showCurrentCard()
        }
    }

    private fun loadParakeet(modelDir: String, numThreads: Int, decodingMethod: String): OfflineRecognizer {
        val modelPath = File(filesDir, modelDir)
        val config = OfflineRecognizerConfig(
            featConfig = FeatureConfig(sampleRate = 16000, featureDim = 80),
            modelConfig = OfflineModelConfig(
                transducer = OfflineTransducerModelConfig(
                    encoder = File(modelPath, "encoder.int8.onnx").absolutePath,
                    decoder = File(modelPath, "decoder.int8.onnx").absolutePath,
                    joiner = File(modelPath, "joiner.int8.onnx").absolutePath,
                ),
                tokens = File(modelPath, "tokens.txt").absolutePath,
                modelType = "nemo_transducer",
                modelingUnit = "bpe",
                bpeVocab = File(modelPath, "bpe.vocab").absolutePath,
                numThreads = numThreads,
                provider = "cpu",
            ),
            decodingMethod = decodingMethod,
            hotwordsScore = 2.0f,
        )
        val t0 = System.nanoTime()
        val recognizer = OfflineRecognizer(config = config)
        parakeetLoadS = (System.nanoTime() - t0) / 1e9
        return recognizer
    }

    private fun loadWhisper(modelDir: String, numThreads: Int): OfflineRecognizer {
        val modelPath = File(filesDir, modelDir)
        val config = OfflineRecognizerConfig(
            featConfig = FeatureConfig(sampleRate = 16000, featureDim = 80),
            modelConfig = OfflineModelConfig(
                whisper = OfflineWhisperModelConfig(
                    encoder = File(modelPath, "small-encoder.int8.onnx").absolutePath,
                    decoder = File(modelPath, "small-decoder.int8.onnx").absolutePath,
                    language = "en",
                    task = "transcribe",
                ),
                tokens = File(modelPath, "small-tokens.txt").absolutePath,
                modelType = "whisper",
                numThreads = numThreads,
                provider = "cpu",
            ),
            decodingMethod = "greedy_search",
        )
        val t0 = System.nanoTime()
        val recognizer = OfflineRecognizer(config = config)
        whisperLoadS = (System.nanoTime() - t0) / 1e9
        whisperConfig = config
        lastWhisperLang = "en"
        return recognizer
    }

    // -------------------------------------------------------------------------------------
    // Deck loading (org.json — already on the Android platform, no new Gradle dependency)
    // and session resume.
    // -------------------------------------------------------------------------------------
    private fun loadDeck(file: File, langMode: String): List<Card> {
        val records = JSONArray(file.readText())
        val langs = if (langMode == "both") listOf("en", "pl") else listOf(langMode)
        val cards = mutableListOf<Card>()
        for (i in 0 until records.length()) {
            val record = records.getJSONObject(i)
            val baseId = record.getString("id")
            for (lang in langs) {
                val side = record.getJSONObject(lang)
                cards.add(
                    Card(
                        baseId = baseId,
                        lang = lang,
                        display = side.getString("display"),
                        canonical = side.getString("canonical"),
                        slotTruth = parseSlotTruth(side.getJSONObject("slotTruth")),
                    ),
                )
            }
        }
        return cards
    }

    private fun parseSlotTruth(json: JSONObject): SlotTruth {
        val particles = jsonStringList(json.optJSONArray("particles"))
        val materials = jsonStringList(json.optJSONArray("materials"))
        val energies = mutableListOf<Pair<String, String>>()
        json.optJSONArray("energies")?.let { arr ->
            for (i in 0 until arr.length()) {
                val e = arr.getJSONObject(i)
                energies.add(formatNumber(e.getDouble("value")) to e.getString("unit"))
            }
        }
        val target = json.optJSONObject("target")?.let {
            formatNumber(it.getDouble("value")) to it.getString("unit")
        }
        return SlotTruth(particles, materials, energies, target)
    }

    private fun jsonStringList(arr: JSONArray?): List<String> {
        if (arr == null) return emptyList()
        return (0 until arr.length()).map { arr.getString(it) }
    }

    private fun formatNumber(v: Double): String =
        if (v == v.toLong().toDouble()) v.toLong().toString() else v.toString()

    /** Reads a prior session.json (if any) and populates `committedCardIds` — the resume path. */
    private fun loadPriorSession() {
        val sessionFile = File(outDir, "session.json")
        if (!sessionFile.exists()) return
        try {
            val takes = JSONArray(sessionFile.readText())
            for (i in 0 until takes.length()) {
                val take = takes.getJSONObject(i)
                val id = take.getString("id")
                val lang = take.getString("lang")
                committedCardIds.add("$id-$lang")
                sessionTakes.add(take.toString())
                val pRecs = parakeetRecords.getOrPut(lang) { mutableListOf() }
                val wRecs = whisperRecords.getOrPut(lang) { mutableListOf() }
                take.optJSONObject("parakeet")?.let {
                    pRecs.add(resultRecordJson(id, it.optString("raw", ""), it.optDouble("secs", 0.0), null))
                }
                take.optJSONObject("whisper")?.let {
                    wRecs.add(resultRecordJson(id, it.optString("raw", ""), it.optDouble("secs", 0.0), null))
                }
            }
        } catch (e: Exception) {
            appendLog("WARNING: failed to parse prior session.json, starting fresh: ${e.message}")
        }
    }

    // -------------------------------------------------------------------------------------
    // Recording (raw 16 kHz mono 16-bit PCM via AudioRecord).
    // -------------------------------------------------------------------------------------
    private fun onRecordTapped() {
        if (!recording) {
            if (checkSelfPermission(Manifest.permission.RECORD_AUDIO) != PackageManager.PERMISSION_GRANTED) {
                appendLog(
                    "Can't record — RECORD_AUDIO not granted yet. Grant it (system dialog, or " +
                        "`adb shell pm grant com.aidedx.sherpabench android.permission.RECORD_AUDIO`) and tap Record again.",
                )
                return
            }
            try {
                startRecordingInternal()
            } catch (e: Exception) {
                appendLog("FAILED to start recording: ${e.message}")
                return
            }
            recordButton.text = "Stop"
            setTakeButtonsEnabled(false)
        } else {
            recordButton.isEnabled = false
            recordButton.text = "Transcribing..."
            val pcm = stopRecordingInternal()
            Thread { transcribeAndShow(pcm) }.start()
        }
    }

    private fun startRecordingInternal() {
        val sampleRate = 16000
        val minBuf = AudioRecord.getMinBufferSize(
            sampleRate,
            AudioFormat.CHANNEL_IN_MONO,
            AudioFormat.ENCODING_PCM_16BIT,
        )
        val bufSize = maxOf(minBuf, sampleRate * 2)
        val record = AudioRecord(
            MediaRecorder.AudioSource.MIC,
            sampleRate,
            AudioFormat.CHANNEL_IN_MONO,
            AudioFormat.ENCODING_PCM_16BIT,
            bufSize,
        )
        synchronized(recordedSamples) { recordedSamples.clear() }
        audioRecord = record
        recording = true
        record.startRecording()
        val thread = Thread {
            val buf = ShortArray(bufSize / 2)
            while (recording) {
                val n = record.read(buf, 0, buf.size)
                if (n > 0) {
                    synchronized(recordedSamples) {
                        for (i in 0 until n) recordedSamples.add(buf[i])
                    }
                }
            }
        }
        readerThread = thread
        thread.start()
    }

    /** Sets `recording = false` and waits for the reader thread's in-flight `read()` call to
     * return and see it (its last iteration) BEFORE calling `stop()`/`release()` — calling
     * those while the reader thread might still be mid-`read()` on the same `AudioRecord` is
     * a real crash risk (`IllegalStateException` on a released object), not hypothetical, so
     * this is ordered deliberately rather than torn down immediately. Runs on the main thread
     * (called directly from the Record/Stop button's click listener) — the wait is bounded by
     * one buffer's read latency (typically well under 100ms), an acceptable tap-to-stop pause. */
    private fun stopRecordingInternal(): ShortArray {
        recording = false
        readerThread?.join(500)
        readerThread = null
        audioRecord?.stop()
        audioRecord?.release()
        audioRecord = null
        return synchronized(recordedSamples) { recordedSamples.toShortArray() }
    }

    private fun toFloatSamples(pcm: ShortArray): FloatArray = FloatArray(pcm.size) { pcm[it] / 32768.0f }

    // -------------------------------------------------------------------------------------
    // Transcription + on-device slot check.
    // -------------------------------------------------------------------------------------
    private fun transcribeAndShow(pcm: ShortArray) {
        val card = deck.getOrNull(cardIndex) ?: return
        val samples = toFloatSamples(pcm)
        val take = Take(pcm)

        try {
            val (raw, secs) = transcribeParakeet(samples)
            take.parakeetRaw = raw
            take.parakeetSecs = secs
        } catch (e: Exception) {
            take.parakeetRaw = "ERROR: ${e.message}"
        }
        try {
            val (raw, secs) = transcribeWhisper(samples, card.lang)
            take.whisperRaw = raw
            take.whisperSecs = secs
        } catch (e: Exception) {
            take.whisperRaw = "ERROR: ${e.message}"
        }

        currentTake = take
        val pHits = checkSlots(take.parakeetRaw, card.slotTruth)
        val wHits = checkSlots(take.whisperRaw, card.slotTruth)

        appendLog(
            "[${card.cardId}]\n" +
                "  parakeet (${"%.2f".format(take.parakeetSecs)}s): ${take.parakeetRaw}  ${pHits.summary()}\n" +
                "  whisper  (${"%.2f".format(take.whisperSecs)}s): ${take.whisperRaw}  ${wHits.summary()}",
        )

        runOnUiThread {
            recordButton.text = "Record"
            setTakeButtonsEnabled(true)
        }
    }

    private fun transcribeParakeet(samples: FloatArray): Pair<String, Double> {
        val recognizer = parakeetRecognizer ?: return "" to 0.0
        val t0 = System.nanoTime()
        val stream = hotwords?.let { recognizer.createStream(it) } ?: recognizer.createStream()
        var text = ""
        stream.use {
            it.acceptWaveform(samples, 16000)
            recognizer.decode(it)
            text = recognizer.getResult(it).text.trim()
        }
        return text to (System.nanoTime() - t0) / 1e9
    }

    private fun transcribeWhisper(samples: FloatArray, lang: String): Pair<String, Double> {
        val recognizer = whisperRecognizer ?: return "" to 0.0
        val config = whisperConfig ?: return "" to 0.0
        if (lastWhisperLang != lang) {
            val updated = config.copy(
                modelConfig = config.modelConfig.copy(
                    whisper = config.modelConfig.whisper.copy(language = lang),
                ),
            )
            recognizer.setConfig(updated)
            whisperConfig = updated
            lastWhisperLang = lang
        }
        val t0 = System.nanoTime()
        val stream = recognizer.createStream()
        var text = ""
        stream.use {
            it.acceptWaveform(samples, 16000)
            recognizer.decode(it)
            text = recognizer.getResult(it).text.trim()
        }
        return text to (System.nanoTime() - t0) / 1e9
    }

    private data class SlotHits(val particle: Boolean, val material: Boolean, val energy: Boolean) {
        fun summary(): String =
            "particle${if (particle) "✓" else "✗"} material${if (material) "✓" else "✗"} energy${if (energy) "✓" else "✗"}"
    }

    /** Literal token containment against a normalized transcript — see the class doc comment
     * for why this is deliberately not the real matcher/corrector. */
    private fun checkSlots(raw: String, slot: SlotTruth): SlotHits {
        val norm = normalizeForCheck(raw)
        val particleOk = slot.particles.isEmpty() || slot.particles.all { regexContains(it, norm) }
        val materialOk = slot.materials.isEmpty() || slot.materials.all { regexContains(it, norm) }
        val energyOk = when {
            slot.target != null -> hasNumber(slot.target.first, norm) && hasUnit(slot.target.second, norm)
            slot.energies.isNotEmpty() -> slot.energies.all { (v, u) -> hasNumber(v, norm) && hasUnit(u, norm) }
            else -> true
        }
        return SlotHits(particleOk, materialOk, energyOk)
    }

    /** Lowercase, strip punctuation, and fold the length-unit spellings this set's own
     * `display` text can contain (English and Polish) back to the abbreviation — same
     * normalization shape as `scripts/asr-score-slots-generic.mjs`'s `norm()`, a reduced
     * subset (no glued-unit digit-boundary handling) since this is a live indicator, not the
     * scoring pass. */
    private fun normalizeForCheck(text: String): String {
        var t = " " + text.lowercase() + " "
        t = t.replace(Regex("[.,?!;:]"), " ")
        t = t.replace(Regex("\\bcentimeters?\\b"), "cm")
        t = t.replace(Regex("\\bmillimeters?\\b"), "mm")
        t = t.replace(Regex("\\bmicrometers?\\b"), "um")
        t = t.replace(Regex("\\bcentymetr(?:y|ów)?\\b"), "cm")
        t = t.replace(Regex("\\bmilimetr(?:y|ów)?\\b"), "mm")
        t = t.replace(Regex("\\bmikrometr(?:y|ów)?\\b"), "um")
        return t
    }

    private fun regexContains(pattern: String, text: String): Boolean =
        try {
            Regex("(?i)(?<![\\p{L}\\d])(?:$pattern)(?![\\p{L}\\d])").containsMatchIn(text)
        } catch (e: Exception) {
            false
        }

    private fun hasNumber(value: String, text: String): Boolean =
        Regex("(?<!\\d)${Regex.escape(value)}(?!\\d)").containsMatchIn(text)

    private fun hasUnit(unit: String, text: String): Boolean =
        Regex("(?i)(?<![a-z])${Regex.escape(unit.lowercase())}(?![a-z])").containsMatchIn(text)

    // -------------------------------------------------------------------------------------
    // Take actions: Keep (commit + advance), Re-record (discard, same card), Skip (advance).
    // -------------------------------------------------------------------------------------
    private fun onKeepTapped() {
        val card = deck.getOrNull(cardIndex) ?: return
        val take = currentTake ?: return
        setTakeButtonsEnabled(false)
        Thread { commitTake(card, take) }.start()
    }

    private fun commitTake(card: Card, take: Take) {
        val wavFile = File(outDir, "${card.cardId}.wav")
        try {
            writeWavFile(wavFile, take.pcm, 16000)
        } catch (e: Exception) {
            appendLog("FAILED to write $wavFile: ${e.message}")
            runOnUiThread { setTakeButtonsEnabled(true) }
            return
        }

        val pHits = checkSlots(take.parakeetRaw, card.slotTruth)
        val wHits = checkSlots(take.whisperRaw, card.slotTruth)
        sessionTakes.add(
            takeJson(card, wavFile.name, take, pHits, wHits),
        )
        parakeetRecords.getOrPut(card.lang) { mutableListOf() }
            .add(resultRecordJson(card.baseId, take.parakeetRaw, take.parakeetSecs, null))
        whisperRecords.getOrPut(card.lang) { mutableListOf() }
            .add(resultRecordJson(card.baseId, take.whisperRaw, take.whisperSecs, null))
        committedCardIds.add(card.cardId)

        writeSessionAndResults()
        appendLog("Kept ${card.cardId} -> $wavFile")

        currentTake = null
        cardIndex++
        runOnUiThread { showCurrentCard() }
    }

    private fun onRerecordTapped() {
        currentTake = null
        setTakeButtonsEnabled(false)
        showCurrentCard()
    }

    private fun onSkipTapped() {
        appendLog("Skipped ${deck.getOrNull(cardIndex)?.cardId}")
        currentTake = null
        cardIndex++
        setTakeButtonsEnabled(false)
        showCurrentCard()
    }

    private fun showCurrentCard() {
