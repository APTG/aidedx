    private fun writeSessionAndResults() {
        writeJsonFile(File(outDir, "session.json"), sessionTakes)
        for ((lang, recs) in parakeetRecords) {
            writeResultsFile(File(outDir, "results-parakeet-$lang.json"), "parakeet-v3", parakeetLoadS, recs)
